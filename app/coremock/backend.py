def customer(user_id: str) -> dict | None:
    if not using_redshift():
        from app.coremock import store

        return store._CUSTOMERS.get(user_id)
    row = _one("SELECT customer_id, name, city, pincode, kyc_status "
               "FROM mcb.customers WHERE user_id = %s", (user_id,))
    if not row:
        return None
    row = _clean(row)
    row["policies"] = [r["policy_id"] for r in _rows(
        "SELECT policy_id FROM mcb.policies WHERE customer_id = %s "
        "ORDER BY policy_id", (row["customer_id"],))]
    return row


def producer(user_id: str) -> dict | None:
    if not using_redshift():
        from app.coremock import store

        return store._PRODUCERS.get(user_id)
    row = _one("SELECT producer_id, name, licence, branch, "
               "TO_CHAR(licence_valid_to, 'YYYY-MM-DD') AS licence_valid_to "
               "FROM mcb.producers WHERE user_id = %s", (user_id,))
    return _clean(row) if row else None


def _hydrate_policy(row: dict) -> dict:
    p = _clean(row)
    pid = p["policy_id"]
    members = _rows("SELECT member_id, name, age, relation "
                    "FROM mcb.policy_members WHERE policy_id = %s "
                    "ORDER BY member_id", (pid,))
    if members:
        p["members"] = [_clean(m) for m in members]
    veh = _one("SELECT registration, make, model, variant, year, fuel, rto "
               "FROM mcb.policy_vehicles WHERE policy_id = %s", (pid,))
    if veh:
        p["vehicle"] = _clean(veh)
    docs = _rows("SELECT document FROM mcb.policy_documents "
                 "WHERE policy_id = %s ORDER BY document", (pid,))
    if docs:
        p["documents"] = [d["document"] for d in docs]
    return p


_POLICY_COLS = ("policy_id, lob, product_id, product_name, customer_id, "
                "status, TO_CHAR(start_date, 'YYYY-MM-DD') AS start_date, "
                "TO_CHAR(end_date, 'YYYY-MM-DD') AS end_date, "
                "TO_CHAR(renewed_to, 'YYYY-MM-DD') AS renewed_to, "
                "sum_insured, idv, ncb_pct")


def policy(policy_id: str) -> dict | None:
    if not using_redshift():
        from app.coremock import store

        return store._POLICIES.get(policy_id)
    row = _one(f"SELECT {_POLICY_COLS} FROM mcb.policies WHERE policy_id = %s",
               (policy_id,))
    return _hydrate_policy(row) if row else None


def policies_for(customer_id: str, lob: str) -> list[dict]:
    if not using_redshift():
        from app.coremock import store

        return [p for p in store._POLICIES.values()
                if p["customer_id"] == customer_id and p["lob"] == lob]
    rows = _rows(f"SELECT {_POLICY_COLS} FROM mcb.policies "
                 "WHERE customer_id = %s AND lob = %s ORDER BY policy_id",
                 (customer_id, lob))
    return [_hydrate_policy(r) for r in rows]


def vehicle(registration: str) -> dict | None:
    if not using_redshift():
        from app.coremock import store

        return store._VEHICLES.get(registration)
    row = _one("SELECT registration, make, model, variant, year, fuel, cc, "
               "vehicle_class, rto, prior_insurer, prior_ncb_pct, "
               "TO_CHAR(prior_expiry, 'YYYY-MM-DD') AS prior_expiry "
               "FROM mcb.vehicles WHERE registration = %s", (registration,))
    return _clean(row) if row else None


def network(kind: str) -> list[dict]:
    if not using_redshift():
        from app.coremock import store

        return list(store._NETWORK.get(kind, []))
    rows = _rows("SELECT name, city, pincode, cashless, km FROM mcb.network "
                 "WHERE kind = %s ORDER BY km", (kind,))
    out = []
    for r in rows:
        r = _clean(r)
        r["km"] = float(r["km"]) if r.get("km") is not None else None
        sp = _rows("SELECT specialty FROM mcb.network_specialties "
                   "WHERE name = %s ORDER BY specialty", (r["name"],))
        if sp:
            r["specialties"] = [s["specialty"] for s in sp]
        out.append(r)
    return out


