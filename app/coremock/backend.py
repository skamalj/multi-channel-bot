"""Where the core record data actually lives.

`store.py` keeps every behaviour that makes the core interesting - latency,
rate limits, gates, idempotency, the refusal to issue a policy whose gates are
not all cleared. None of that changes when the rows move to Redshift. What
changes is only where a row is read from, so that is the one thing behind an
interface.

Two backends, chosen by configuration:

* **memory** - the dicts in `store.py`. What the 164 offline tests run
  against, and what `NO_AWS=1` gives you with no credentials at all.
* **redshift** - the same rows, in the schema generated by
  `scripts/gen_seed_sql.py`.

The seam is deliberately narrow. A backend answers questions about records;
it does not know what a gate is, or that a motor policy cannot be issued
before an inspection passes. Push that logic down here and it would have to
exist twice, and the two copies would disagree.

**psycopg2, not psycopg3.** Redshift reports its client encoding as `UNICODE`,
which Python has no codec for; psycopg2 maps it to `utf_8` and psycopg3 does
not. Found by a Lambda that connected fine and then failed on its first query.
"""
from __future__ import annotations

import json
import logging
import threading

from app.config import settings

log = logging.getLogger("mcb.core.backend")

_LOCAL = threading.local()


def using_redshift() -> bool:
    cfg = settings()
    import os

    if os.getenv("NO_AWS") == "1" or cfg.no_aws:
        return False
    return bool(cfg.redshift_host)


# ---------------------------------------------------------------------------
# connection
# ---------------------------------------------------------------------------
def _conn():
    """One connection per thread, reopened if the server dropped it.

    Redshift Serverless pauses when idle and a pooled connection does not
    survive that, so a dead connection is replaced rather than raised - the
    first query after an idle period should wake the warehouse, not fail.
    """
    c = getattr(_LOCAL, "conn", None)
    if c is not None:
        try:
            if not c.closed:
                return c
        except Exception:                                    # noqa: BLE001
            pass
    import psycopg2

    cfg = settings()
    c = psycopg2.connect(
        host=cfg.redshift_host, port=cfg.redshift_port,
        dbname=cfg.redshift_db, user=cfg.redshift_user,
        password=cfg.redshift_password, connect_timeout=30)
    c.autocommit = True
    _LOCAL.conn = c
    return c


def _rows(sql: str, args: tuple = ()) -> list[dict]:
    with _conn().cursor() as cur:
        cur.execute(sql, args)
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, r)) for r in cur.fetchall()]


def _exec(sql: str, args: tuple = ()) -> None:
    with _conn().cursor() as cur:
        cur.execute(sql, args)


def _one(sql: str, args: tuple = ()) -> dict | None:
    rows = _rows(sql, args)
    return rows[0] if rows else None


def _clean(d: dict) -> dict:
    """Drop NULL columns so a Redshift row reads like the dict it replaced.

    A motor policy has no `sum_insured` and a health policy has no `idv`. In
    the fixtures those keys are simply absent; in SQL they are NULL. Leaving
    them in would make `"sum_insured" in policy` true for a motor policy,
    which is the kind of difference that only shows up in an answer.
    """
    return {k: v for k, v in d.items() if v is not None}


