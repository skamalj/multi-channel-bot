def ledger_get(key: str) -> dict | None:
    """The recorded outcome of a write that already happened, or None.

    The digest check that decides whether a replayed key carries the SAME
    payload stays in store.py. This only stores and returns; it does not know
    what makes a replay legitimate.
    """
    if not using_redshift():
        from app.coremock import store

        return store._IDEMPOTENCY.get(key)
    row = _one("SELECT result_json FROM mcb.write_ledger "
               "WHERE idempotency_key = %s", (key,))
    return json.loads(row["result_json"]) if row and row.get("result_json") else None


def ledger_put(key: str, op: str, record: dict) -> dict:
    """Record a write, and return what the ledger holds afterwards.

    Redshift enforces no unique constraint and has no `ON CONFLICT`, so the
    insert is guarded by `WHERE NOT EXISTS` and then READ BACK. The read-back
    is the point: if a concurrent caller won, their result is the one both
    must return, or a retried payment_collect would report two different
    receipts for one payment.

    Worth being precise about the guarantee. Two exactly simultaneous callers
    could both see no row and both attempt the insert; the guard makes the
    second a no-op and the read-back makes them agree. Sequential retries -
    which is what a channel actually produces - are exact.
    """
    if not using_redshift():
        from app.coremock import store

        store._IDEMPOTENCY[key] = record
        return record
    _exec("INSERT INTO mcb.write_ledger (idempotency_key, tool_name, "
          "user_id, result_json) SELECT %s, %s, %s, %s WHERE NOT EXISTS "
          "(SELECT 1 FROM mcb.write_ledger WHERE idempotency_key = %s)",
          (key, op, "", json.dumps(record, default=str), key))
    return ledger_get(key) or record


def reset_connection() -> None:
    c = getattr(_LOCAL, "conn", None)
    if c is not None:
        try:
            c.close()
        except Exception:                                    # noqa: BLE001
            pass
    _LOCAL.conn = None
