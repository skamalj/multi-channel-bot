def put_policy(p: dict) -> None:
    """A newly issued policy. Delete-then-insert: Redshift has no upsert."""
    if not using_redshift():
        from app.coremock import store

        store._POLICIES[p["policy_id"]] = p
        return
    pid = p["policy_id"]
    for t in ("policies", "policy_members", "policy_vehicles",
              "policy_documents"):
        _exec(f"DELETE FROM mcb.{t} WHERE policy_id = %s", (pid,))
    _exec("INSERT INTO mcb.policies (policy_id, lob, product_id, "
          "product_name, customer_id, status, start_date, end_date, "
          "renewed_to, sum_insured, idv, ncb_pct) "
          "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
          (pid, p.get("lob"), p.get("product_id"), p.get("product_name"),
           p.get("customer_id"), p.get("status"), p.get("start_date"),
           p.get("end_date"), p.get("renewed_to"), p.get("sum_insured"),
           p.get("idv"), p.get("ncb_pct")))
    for m in p.get("members") or []:
        _exec("INSERT INTO mcb.policy_members (policy_id, member_id, name, "
              "age, relation) VALUES (%s,%s,%s,%s,%s)",
              (pid, m.get("member_id"), m.get("name"), m.get("age"),
               m.get("relation")))
    v = p.get("vehicle")
    if v:
        _exec("INSERT INTO mcb.policy_vehicles (policy_id, registration, "
              "make, model, variant, year, fuel, rto) "
              "VALUES (%s,%s,%s,%s,%s,%s,%s,%s)",
              (pid, v.get("registration"), v.get("make"), v.get("model"),
               v.get("variant"), v.get("year"), v.get("fuel"), v.get("rto")))
    for d in p.get("documents") or []:
        _exec("INSERT INTO mcb.policy_documents (policy_id, document) "
              "VALUES (%s,%s)", (pid, d))


def _doc_put(table: str, key_col: str, key: str, cols: dict,
             body: dict) -> None:
    names = ", ".join([key_col, *cols.keys(), "body"])
    marks = ", ".join(["%s"] * (len(cols) + 2))
    _exec(f"DELETE FROM mcb.{table} WHERE {key_col} = %s", (key,))
    _exec(f"INSERT INTO mcb.{table} ({names}) VALUES ({marks})",
          (key, *cols.values(), json.dumps(body, default=str)))


def _doc_get(table: str, key_col: str, key: str) -> dict | None:
    row = _one(f"SELECT body FROM mcb.{table} WHERE {key_col} = %s", (key,))
    return json.loads(row["body"]) if row and row.get("body") else None


